"""
ProteinLens-OS SQLite Persistence Layer (SQLModel)
Zero external DB install required; stores:
- ClinicalCase (saved analyses, variants, clinician/student notes, SHA-256 checksums)
- BatchJob (async multi-variant triage jobs & ranked outputs)
- InstitutionConfig (white-label college/lab branding for exported dossiers)
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Optional
from sqlmodel import Field, Session, SQLModel, create_engine, select


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


class ClinicalCase(SQLModel, table=True):
    id: Optional[int] = Field(default=None, primary_key=True)
    case_code: str = Field(index=True)
    title: str
    protein_name: str
    uniprot_id: Optional[str] = None
    gene_symbol: Optional[str] = None
    mutation: Optional[str] = None
    composite_risk_score: Optional[float] = None
    evolutionary_llr: Optional[float] = None
    risk_tier: Optional[str] = None
    sequence_sha256: str
    clinician_notes: str = ""
    mode: str = "research"  # clinical | research | student
    payload_json: str  # Full serialized analysis snapshot for instant reload & audit
    created_at: str = Field(default_factory=utc_now_iso)


class BatchJob(SQLModel, table=True):
    id: Optional[int] = Field(default=None, primary_key=True)
    job_uid: str = Field(index=True, unique=True)
    title: str
    status: str = "queued"  # queued | running | completed | failed
    total_items: int = 0
    completed_items: int = 0
    results_json: str = "[]"
    error_message: Optional[str] = None
    created_at: str = Field(default_factory=utc_now_iso)
    updated_at: str = Field(default_factory=utc_now_iso)


class InstitutionConfig(SQLModel, table=True):
    id: Optional[int] = Field(default=1, primary_key=True)
    institution_name: str = "IIIT Nagpur — Computational Biology & AI Lab"
    department: str = "Department of Computer Science & Engineering"
    location: str = "Nagpur, Maharashtra, India"
    report_disclaimer: str = (
        "Generated by ProteinLens-OS (Local-First Open-Source Platform). "
        "For Research, Academic Teaching, and Clinical Decision Support Only — "
        "not a standalone FDA/CDSCO diagnostic."
    )
    default_audience_mode: str = "clinical"
    updated_at: str = Field(default_factory=utc_now_iso)


class DatabaseManager:
    def __init__(self, db_path: Path):
        self.db_path = db_path
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        self.engine = create_engine(
            f"sqlite:///{db_path.as_posix()}",
            connect_args={"check_same_thread": False},
        )
        SQLModel.metadata.create_all(self.engine)
        self._ensure_default_institution()

    def _ensure_default_institution(self) -> None:
        with Session(self.engine) as session:
            existing = session.exec(select(InstitutionConfig).where(InstitutionConfig.id == 1)).first()
            if not existing:
                session.add(InstitutionConfig(id=1))
                session.commit()

    def get_session(self) -> Session:
        return Session(self.engine)
