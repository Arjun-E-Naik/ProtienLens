"use client";

import React, { createContext, useCallback, useContext, useEffect, useState } from "react";
import { api } from "@/lib/api";
import type {
  AIRouterStatus,
  ClinicalVariantPreset,
  InstitutionConfig,
  ProteinAnalysisResponse,
  ProteinPreset,
  TeachingLab,
  VariantAnalysisResponse,
} from "@/lib/types";

interface WorkspaceContextValue {
  darkMode: boolean;
  toggleDarkMode: () => void;
  institution: InstitutionConfig;
  aiStatus: AIRouterStatus | null;
  backendOnline: boolean;
  presets: ProteinPreset[];
  clinicalVariants: ClinicalVariantPreset[];
  teachingLabs: TeachingLab[];
  activeProtein: ProteinAnalysisResponse | null;
  setActiveProtein: (p: ProteinAnalysisResponse | null) => void;
  activeVariant: VariantAnalysisResponse | null;
  setActiveVariant: (v: VariantAnalysisResponse | null) => void;
  refreshSystemState: () => Promise<void>;
  runQuickProtein: (opts: { uniprot_id?: string; sequence?: string; protein_name?: string }) => Promise<ProteinAnalysisResponse>;
  isLoadingProtein: boolean;
}

const DEFAULT_INSTITUTION: InstitutionConfig = {
  institution_name: "IIIT Nagpur — Computational Biology & AI Lab",
  department: "Department of Computer Science & Engineering",
  location: "Nagpur, Maharashtra, India",
  report_disclaimer:
    "Generated by ProteinLens-OS (Local-First Open-Source Platform). For Research, Academic Teaching, and Clinical Decision Support Only.",
  default_audience_mode: "clinical",
};

const WorkspaceContext = createContext<WorkspaceContextValue | undefined>(undefined);

export function WorkspaceProvider({ children }: { children: React.ReactNode }) {
  const [darkMode, setDarkMode] = useState(false);
  const [institution, setInstitution] = useState<InstitutionConfig>(DEFAULT_INSTITUTION);
  const [aiStatus, setAiStatus] = useState<AIRouterStatus | null>(null);
  const [backendOnline, setBackendOnline] = useState(false);
  const [presets, setPresets] = useState<ProteinPreset[]>([]);
  const [clinicalVariants, setClinicalVariants] = useState<ClinicalVariantPreset[]>([]);
  const [teachingLabs, setTeachingLabs] = useState<TeachingLab[]>([]);
  const [activeProtein, setActiveProtein] = useState<ProteinAnalysisResponse | null>(null);
  const [activeVariant, setActiveVariant] = useState<VariantAnalysisResponse | null>(null);
  const [isLoadingProtein, setIsLoadingProtein] = useState(false);

  useEffect(() => {
    const savedTheme = typeof window !== "undefined" ? localStorage.getItem("plos-theme") : null;
    if (savedTheme === "dark") {
      setDarkMode(true);
      document.documentElement.classList.add("dark");
    }
  }, []);

  const toggleDarkMode = useCallback(() => {
    setDarkMode((prev) => {
      const next = !prev;
      if (next) {
        document.documentElement.classList.add("dark");
        localStorage.setItem("plos-theme", "dark");
      } else {
        document.documentElement.classList.remove("dark");
        localStorage.setItem("plos-theme", "light");
      }
      return next;
    });
  }, []);

  const refreshSystemState = useCallback(async () => {
    try {
      const [h, pr] = await Promise.all([api.health(), api.presets()]);
      setBackendOnline(true);
      setInstitution(h.institution);
      setAiStatus(h.ai_router);
      setPresets(pr.proteins);
      setClinicalVariants(pr.clinical_variants);
      setTeachingLabs(pr.teaching_labs);
    } catch {
      setBackendOnline(false);
    }
  }, []);

  useEffect(() => {
    refreshSystemState();
  }, [refreshSystemState]);

  const runQuickProtein = useCallback(
    async (opts: { uniprot_id?: string; sequence?: string; protein_name?: string }) => {
      setIsLoadingProtein(true);
      try {
        const res = await api.analyzeProtein({
          ...opts,
          min_confidence: 0.2,
          include_bio_evidence: true,
        });
        setActiveProtein(res);
        return res;
      } finally {
        setIsLoadingProtein(false);
      }
    },
    []
  );

  return (
    <WorkspaceContext.Provider
      value={{
        darkMode,
        toggleDarkMode,
        institution,
        aiStatus,
        backendOnline,
        presets,
        clinicalVariants,
        teachingLabs,
        activeProtein,
        setActiveProtein,
        activeVariant,
        setActiveVariant,
        refreshSystemState,
        runQuickProtein,
        isLoadingProtein,
      }}
    >
      {children}
    </WorkspaceContext.Provider>
  );
}

export function useWorkspace() {
  const ctx = useContext(WorkspaceContext);
  if (!ctx) {
    throw new Error("useWorkspace must be used within WorkspaceProvider");
  }
  return ctx;
}
